const { readFileSync, writeFileSync } = require('node:fs');
const { resolve, extname } = require('node:path');

const root = resolve(__dirname, '..');
const registry = JSON.parse(readFileSync(resolve(root, 'challenge-icons/registry.template.json'), 'utf8'));
const paths = new Set([
  ...Object.values(registry.ui),
  ...Object.values(registry.countdown),
  ...registry.challenges.map(entry => entry.assetPath)
]);
const mime = { '.gif': 'image/gif', '.png': 'image/png' };
const assets = {};
for (const assetPath of [...paths].sort()) {
  const mediaType = mime[extname(assetPath).toLowerCase()];
  if (!mediaType) throw new Error(`Unsupported icon format: ${assetPath}`);
  const bytes = readFileSync(resolve(root, assetPath));
  assets[assetPath] = `data:${mediaType};base64,${bytes.toString('base64')}`;
}
writeFileSync(
  resolve(root, 'apps/telemetry-inspector/src/generatedIconAssets.ts'),
  `// Generated by scripts/generate-icon-assets.cjs. Do not edit.\nexport const EMBEDDED_ICON_ASSETS: Readonly<Record<string, string>> = ${JSON.stringify(assets, null, 2)};\n`
);
