const { existsSync, readFileSync, writeFileSync } = require('node:fs');
const { extname, resolve } = require('node:path');

const root = resolve(__dirname, '..');
const paths = JSON.parse(readFileSync(resolve(root, 'res/progression-assets.template.json'), 'utf8'));
const mime = { '.gif': 'image/gif', '.png': 'image/png' };
const assets = {};
const missing = [];

for (const [assetId, assetPath] of Object.entries(paths)) {
  if (typeof assetPath !== 'string' || !assetPath.startsWith('res/')) {
    throw new Error(`Invalid progression asset path for ${assetId}.`);
  }
  const mediaType = mime[extname(assetPath).toLowerCase()];
  if (!mediaType) throw new Error(`Unsupported progression asset format: ${assetPath}`);
  const absolutePath = resolve(root, assetPath);
  if (!existsSync(absolutePath)) {
    missing.push(assetPath);
    continue;
  }
  assets[assetId] = `data:${mediaType};base64,${readFileSync(absolutePath).toString('base64')}`;
}

writeFileSync(
  resolve(root, 'apps/telemetry-inspector/src/generatedProgressionAssets.ts'),
  [
    '// Generated by scripts/generate-progression-assets.cjs. Do not edit.',
    `export const PROGRESSION_ASSET_PATHS = ${JSON.stringify(paths, null, 2)} as const;`,
    'export type ProgressionAssetId = keyof typeof PROGRESSION_ASSET_PATHS;',
    `export const EMBEDDED_PROGRESSION_ASSETS: Readonly<Partial<Record<ProgressionAssetId, string>>> = ${JSON.stringify(assets, null, 2)};`,
    ''
  ].join('\n')
);

console.log(JSON.stringify({
  progressionAssets: {
    embedded: Object.keys(assets),
    missing,
    embeddedCount: Object.keys(assets).length,
    registeredCount: Object.keys(paths).length
  }
}, null, 2));
