const { readdirSync, readFileSync, writeFileSync } = require('node:fs');
const { resolve, extname, basename } = require('node:path');
const root = resolve(__dirname, '..');
const statExclusions = new Set([
  'best-guess-time.gif', 'challenges-completed.gif', 'drawing-effectiveness.gif', 'drawing-reactions.png',
  'drawing-rounds.gif', 'drawing-round-score.gif', 'first-guesser-rate.gif', 'guess-accuracy.gif',
  'guess-attempts.gif', 'longest-session.gif', 'observed-play-time.gif', 'p90-guess-time.gif',
  'play-days.gif', 'play-day-streak.gif', 'skribbl-win-rate.gif', 'skribbl-wins.gif',
  'skribbl-win-streak.gif', 'submitted-messages.gif'
]);
const groups = [
  ['challenge', 'res/challenge-icons', file => file !== 'one-line.gif'],
  ['friend', 'res/friend-system', file => ['block.gif', 'friends-list.gif', 'ping.gif'].includes(file)],
  ['skribble', 'res/skribble-icons', file => ['correct.gif', 'incorrect.gif', 'semicorrect.gif', 'skribbl-coin.gif'].includes(file)],
  ['slot', 'res/skribbl-slots/slot-icons', file => ['7.gif', 'eraser.gif', 'heart.gif'].includes(file)],
  ['stat', 'res/stat-icons', file => !statExclusions.has(file)]
];
const registry = [];
for (const [group, directory, include] of groups) {
  for (const file of readdirSync(resolve(root, directory)).sort()) {
    if (!['.gif', '.png'].includes(extname(file)) || !include(file)) continue;
    const slug = basename(file, extname(file)).toLowerCase();
    registry.push({ group, path: `${directory}/${file}`, token: `:${group}/${slug}:`, label: slug.replace(/[-_]/g, ' ') });
  }
}
const challengeRegistry = JSON.parse(readFileSync(resolve(root, 'res/challenge-icons/registry.template.json')));
const statRegistry = JSON.parse(readFileSync(resolve(root, 'res/stat-icons/registry.template.json')));
const progression = JSON.parse(readFileSync(resolve(root, 'res/progression-assets.template.json')));
const embedded = new Set([...Object.values(challengeRegistry.ui), ...Object.values(challengeRegistry.countdown),
  ...challengeRegistry.challenges.map(item => item.assetPath), ...Object.values(progression),
  ...statRegistry.stats.map(item => item.assetPath), ...Object.values(statRegistry.utilities)]);
const additional = Object.fromEntries(registry.filter(item => !embedded.has(item.path)).map(item => [item.path,
  `data:image/${extname(item.path) === '.png' ? 'png' : 'gif'};base64,${readFileSync(resolve(root, item.path)).toString('base64')}`]));
writeFileSync(resolve(root, 'apps/telemetry-inspector/src/generatedSocialEmojiAssets.ts'),
  '// Generated by scripts/generate-social-emoji-assets.cjs. Do not edit.\n'
  + `export const SOCIAL_EMOJI_DEFINITIONS = ${JSON.stringify(registry, null, 2)} as const;\n`
  + `export const ADDITIONAL_SOCIAL_EMOJI_ASSETS: Readonly<Record<string, string>> = ${JSON.stringify(additional)};\n`);
console.log(`Registered ${registry.length} Social emojis (${Object.keys(additional).length} additional embedded assets).`);
