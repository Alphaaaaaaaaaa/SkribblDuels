function normalizeWord(value) {
  return value
    .normalize('NFKC')
    .toLocaleLowerCase()
    .replace(/[’‘]/gu, "'")
    .replace(/^[^\p{L}\p{M}]+|[^\p{L}\p{M}]+$/gu, '');
}

function hash32(value, seed) {
  let hash = seed >>> 0;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash >>> 0;
}

function createBloom(items) {
  const bitCount = Math.max(1_024, Math.ceil(items.length * BITS_PER_ITEM / 8) * 8);
  const bytes = Buffer.alloc(bitCount / 8);
  for (const item of items) {
    const first = hash32(item, 0x811c9dc5);
    const second = hash32(item, 0x9e3779b9) | 1;
    for (let index = 0; index < HASH_COUNT; index += 1) {
      const bit = ((first + Math.imul(index, second)) >>> 0) % bitCount;
      bytes[bit >>> 3] |= 1 << (bit & 7);
    }
  }
  return {
    bitCount,
    hashCount: HASH_COUNT,
    itemCount: items.length,
    base64: bytes.toString('base64')
  };
}

function deletionVariants(value) {
  const characters = Array.from(value);
  if (characters.length < 5) return [];
  const variants = new Set();
  for (let index = 0; index < characters.length; index += 1) {
    variants.add([...characters.slice(0, index), ...characters.slice(index + 1)].join(''));
  }
  return [...variants];
}

function digest(value) {
  return createHash('sha256').update(value).digest('hex');
}

async function loadLanguage([languageId, languageName, code, locale, year]) {
  const source = `${SOURCE_BASE}/${year}/${code}/${code}_50k.txt`;
  const response = await fetch(source);
  if (!response.ok) throw new Error(`${languageName}: HTTP ${response.status} from ${source}`);
  const raw = await response.text();
  const words = [];
  const seen = new Set();
  for (const line of raw.split(/\r?\n/u)) {
    const separator = line.lastIndexOf(' ');
    const word = normalizeWord(separator >= 0 ? line.slice(0, separator) : line);
    if (!word || seen.has(word) || !/\p{L}/u.test(word) || /\s/u.test(word)) continue;
    seen.add(word);
    words.push(word);
    if (words.length >= WORD_LIMIT) break;
  }
  if (words.length < WORD_LIMIT) {
    throw new Error(`${languageName}: only ${words.length} usable words were available.`);
  }
  const deletions = new Set();
  for (const word of words) {
    for (const variant of deletionVariants(word)) deletions.add(variant);
  }
  return {
    languageId,
    languageName,
    locale,
    source,
    sourceSha256: digest(raw),
    selectedWordsSha256: digest(words.join('\n')),
    exact: createBloom(words),
    deletions: createBloom([...deletions])
  };
}

