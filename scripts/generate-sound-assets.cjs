const { existsSync, readFileSync, writeFileSync } = require('node:fs');
const { resolve, extname } = require('node:path');

const root = resolve(__dirname, '..');
const registryPath = resolve(root, 'sound-effects/registry.template.json');
const registry = JSON.parse(readFileSync(registryPath, 'utf8'));
const entries = Object.entries(registry.sounds ?? {});
const supported = {
  '.ogg': 'audio/ogg',
  '.mp3': 'audio/mpeg',
  '.wav': 'audio/wav'
};
const seenPaths = new Set();
const assets = {};
const paths = {};
const missing = [];

for (const [soundId, assetPath] of entries) {
  if (typeof soundId !== 'string' || !/^[A-Za-z][A-Za-z0-9]*$/.test(soundId)) {
    throw new Error(`Invalid sound registry id: ${String(soundId)}`);
  }
  if (typeof assetPath !== 'string' || !assetPath.startsWith('sound-effects/')) {
    throw new Error(`Invalid sound asset path for ${soundId}: ${String(assetPath)}`);
  }
  const mediaType = supported[extname(assetPath).toLowerCase()];
  if (!mediaType) throw new Error(`Unsupported sound format: ${assetPath}`);
  if (seenPaths.has(assetPath)) throw new Error(`Duplicate sound asset path: ${assetPath}`);
  seenPaths.add(assetPath);
  paths[soundId] = assetPath;
  const absolutePath = resolve(root, assetPath);
  if (!existsSync(absolutePath)) {
    missing.push(assetPath);
    continue;
  }
  const bytes = readFileSync(absolutePath);
  assets[soundId] = `data:${mediaType};base64,${bytes.toString('base64')}`;
}

writeFileSync(
  resolve(root, 'apps/telemetry-inspector/src/generatedSoundAssets.ts'),
  [
    '// Generated by scripts/generate-sound-assets.cjs. Do not edit.',
    `export const SOUND_ASSET_PATHS = ${JSON.stringify(paths, null, 2)} as const;`,
    'export type SoundEffectId = keyof typeof SOUND_ASSET_PATHS;',
    `export const EMBEDDED_SOUND_ASSETS: Readonly<Partial<Record<SoundEffectId, string>>> = ${JSON.stringify(assets, null, 2)};`,
    ''
  ].join('\n')
);

console.log(JSON.stringify({
  soundRegistry: {
    embedded: Object.keys(assets),
    missing,
    embeddedCount: Object.keys(assets).length,
    registeredCount: entries.length
  }
}, null, 2));
