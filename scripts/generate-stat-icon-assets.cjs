const { existsSync, readFileSync, writeFileSync } = require('node:fs');
const { extname, resolve } = require('node:path');

const root = resolve(__dirname, '..');
const registry = JSON.parse(readFileSync(resolve(root, 'stat-icons/registry.template.json'), 'utf8'));
const mime = { '.gif': 'image/gif', '.png': 'image/png' };
const statPaths = Object.fromEntries(registry.stats.map(entry => [entry.statId, entry.assetPath]));
const utilityPaths = registry.utilities;
const paths = [...new Set([...Object.values(statPaths), ...Object.values(utilityPaths)])].sort();
const assets = {};
const missing = [];

for (const assetPath of paths) {
  const mediaType = mime[extname(assetPath).toLowerCase()];
  if (!mediaType) throw new Error(`Unsupported stat icon format: ${assetPath}`);
  const absolutePath = resolve(root, assetPath);
  if (!existsSync(absolutePath)) {
    missing.push(assetPath);
    continue;
  }
  assets[assetPath] = `data:${mediaType};base64,${readFileSync(absolutePath).toString('base64')}`;
}

writeFileSync(
  resolve(root, 'apps/telemetry-inspector/src/generatedStatIconAssets.ts'),
  [
    '// Generated by scripts/generate-stat-icon-assets.cjs. Do not edit.',
    `export const EMBEDDED_STAT_ICON_ASSETS: Readonly<Record<string, string>> = ${JSON.stringify(assets, null, 2)};`,
    `export const STAT_ICON_ASSET_PATHS = ${JSON.stringify(statPaths, null, 2)} as const;`,
    `export const STAT_UTILITY_ICON_ASSET_PATHS = ${JSON.stringify(utilityPaths, null, 2)} as const;`,
    ''
  ].join('\n')
);

console.log(JSON.stringify({
  statIconRegistry: {
    embeddedCount: Object.keys(assets).length,
    registeredCount: paths.length,
    missing
  }
}, null, 2));
